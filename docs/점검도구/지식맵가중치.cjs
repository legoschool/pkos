const assert=require('node:assert/strict');
require('../../knowledge-graph.js');
const g=globalThis.PKOSGraph;
const records=[{id:'a',title:'분수',text:'AI 수직선 수직선',path:['가','수학'],tags:['수학']},{id:'b',title:'분수',text:'인공지능 수직선',path:['나','수학'],tags:['수학']},{id:'c',title:'음악',text:'리듬',path:['음악'],tags:[]}];
const base={stem:w=>w,text:n=>n.text,path:n=>n.path,links:()=>[]};
const run=o=>g.analyze(records,{...base,...o});
assert.equal(run().edges.length,1);
assert.equal(run().degree.get('a'),1);
assert.equal(run().edges[0].words.length,1);
assert.equal(run({selected:['similar']}).edges[0].score,100);
assert.equal(run({synonyms:false}).edges[0].words.length,1);
assert.equal(run({mode:'folder'}).edges[0].score,25);
assert.equal(run({mode:'direct'}).edges.length,0);
assert.equal(run({threshold:100,links:(a,b)=>a==='a'&&b==='c'?['근거']:[]}).edges[0].direct,true);
assert.equal(run({mode:'body',minWords:3}).edges.length,0);
assert.equal(run({weights:{body:0,title:0,tag:0,folder:0}}).edges.length,0);
assert.equal(run({selected:[]}).edges.length,0);
assert.equal(run({selected:['folder','title']}).edges.length,1);
assert.equal(run({selected:['folder'],folderKinds:['same']}).edges.length,0);
assert.equal(run({selected:['folder'],folderKinds:['name']}).edges.length,1);
assert.equal(run({selected:['folder'],links:()=>['수동']}).edges[0].direct,false);
assert.equal(g.matches(records[0],'수직선',['title'],n=>n.text,n=>n.path),false);
assert.equal(g.matches(records[0],'수직선',['body'],n=>n.text,n=>n.path),true);
assert.equal(g.matches(records[0],'수학',['folder'],n=>n.text,n=>n.path),true);
assert.equal(g.matches(records[0],'분수 수학',['title','folder'],n=>n.text,n=>n.path),true);
assert.deepEqual([0,2,3,5,6,9,10,30].map(g.shape),[0,0,6,6,8,8,10,10]);
console.log('PASS weighted graph: criteria, aliases, thresholds, unique neighbors, shapes');
